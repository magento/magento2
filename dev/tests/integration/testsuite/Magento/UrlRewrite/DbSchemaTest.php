declare(strict_types=1);

namespace Magento\UrlRewrite;

use Magento\Framework\App\ObjectManager;
use Magento\Framework\App\ResourceConnection;
use Magento\Framework\DB\Adapter\AdapterInterface;
use Monolog\Test\TestCase;
use PHPUnit\Framework\Attributes\DataProvider;

class DbSchemaTest extends TestCase
{
    /**
     * @param string $tableName
     * @param string $indexName
     * @param array $columns
     * @param string $indexType
     * @return void
     */
    #[DataProvider('indexDataProvider')]
    public function testIndex(
        string $tableName,
        string $indexName,
        array $columns,
        string $indexType = AdapterInterface::INDEX_TYPE_INDEX,
    ): void {
        $connection = ObjectManager::getInstance()->get(ResourceConnection::class)->getConnection();
        $indexes = $connection->getIndexList($tableName);
        $this->assertArrayHasKey($indexName, $indexes);
        $this->assertSame($columns, $indexes[$indexName]['COLUMNS_LIST']);
        $this->assertSame($indexType, $indexes[$indexName]['INDEX_TYPE']);
    }

    /**
     * @return array[]
     */
    public static function indexDataProvider(): array
    {
        return [
            [
                'url_rewrite',
                'URL_REWRITE_ENTITY_TYPE_METADATA_IS_AUTOGENERATED',
                ['entity_type', 'metadata', 'is_autogenerated']
            ]
        ];
    }

    /**
     * @param string $tableName
     * @param string $indexName
     * @return void
     */
    #[DataProvider('removedIndexDataProvider')]
    public function testIndexRemoved(string $tableName, string $indexName): void
    {
        $connection = ObjectManager::getInstance()->get(ResourceConnection::class)->getConnection();
        $indexes = $connection->getIndexList($tableName);
        $this->assertArrayNotHasKey($indexName, $indexes);
    }

    /**
     * @return array[]
     */
    public static function removedIndexDataProvider(): array
    {
        return [
            [
                'url_rewrite',
                'URL_REWRITE_IS_AUTOGENERATED_METADATA'
            ]
        ];
    }
}
