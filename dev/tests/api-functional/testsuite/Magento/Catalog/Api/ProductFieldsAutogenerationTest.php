namespace Magento\Catalog\Api;

use Magento\Catalog\Api\Data\ProductInterface;
use Magento\Catalog\Model\Product\Attribute\Source\Status;
use Magento\Catalog\Model\Product\Type;
use Magento\Catalog\Model\Product\Visibility;
use Magento\Catalog\Test\Fixture\Product as ProductFixture;
use Magento\Framework\Webapi\Rest\Request;
use Magento\TestFramework\Fixture\Config;
use Magento\TestFramework\Fixture\DataFixture;
use Magento\TestFramework\Fixture\DataFixtureStorageManager;
use Magento\TestFramework\TestCase\WebapiAbstract;

/**
 * Tests the "Product Fields Auto-Generation" masks for products saved through the web API.
 */
class ProductFieldsAutogenerationTest extends WebapiAbstract
{
    private const RESOURCE_PATH = '/V1/products';
    private const SERVICE_NAME = 'catalogProductRepositoryV1';
    private const CONFIG_APPLY_TO_API = 'catalog/fields_masks_api/enabled';

    /**
     * @var bool
     */
    private bool $productCreated = false;

    /**
     * @var string
     */
    private string $sku;

    /**
     * @inheritdoc
     */
    protected function setUp(): void
    {
        parent::setUp();
        $this->sku = 'product-fields-autogeneration-' . uniqid();
    }

    /**
     * @inheritdoc
     */
    protected function tearDown(): void
    {
        if ($this->productCreated) {
            $this->_webApiCall(
                [
                    'rest' => [
                        'resourcePath' => self::RESOURCE_PATH . '/' . $this->sku,
                        'httpMethod' => Request::HTTP_METHOD_DELETE,
                    ],
                    'soap' => [
                        'service' => self::SERVICE_NAME,
                        'serviceVersion' => 'V1',
                        'operation' => self::SERVICE_NAME . 'DeleteById',
                    ],
                ],
                ['sku' => $this->sku]
            );
        }
        parent::tearDown();
    }

    /**
     * With the default configuration a new product keeps its meta fields empty.
     *
     * @return void
     */
    public function testNewProductIsNotAutogeneratedByDefault(): void
    {
        $product = $this->saveProduct($this->getNewProductData([
            ['attribute_code' => 'description', 'value' => 'Some text'],
        ]));
        $this->productCreated = true;

        $attributes = $this->getCustomAttributes($product);
        $this->assertArrayNotHasKey('meta_title', $attributes);
        $this->assertArrayNotHasKey('meta_keyword', $attributes);
        $this->assertArrayNotHasKey('meta_description', $attributes);
    }

    /**
     * Empty meta fields of a new product are generated from the masks, HTML is stripped.
     *
     * The description mask is set here because Magento_PageBuilder changes its default to {{name}}.
     *
     * @return void
     */
    #[
        Config(self::CONFIG_APPLY_TO_API, 1),
        Config('catalog/fields_masks/meta_description', '{{name}} {{description}}'),
    ]
    public function testNewProductGetsMetaFieldsFromMasks(): void
    {
        $product = $this->saveProduct($this->getNewProductData([
            ['attribute_code' => 'description', 'value' => '<p>Some <b>text</b></p>'],
        ]));
        $this->productCreated = true;

        $attributes = $this->getCustomAttributes($product);
        $this->assertSame('Autogeneration', $attributes['meta_title'] ?? null);
        $this->assertSame('Autogeneration', $attributes['meta_keyword'] ?? null);
        $this->assertSame('Autogeneration Some text', $attributes['meta_description'] ?? null);
    }

    /**
     * A value sent in the request wins over the mask.
     *
     * @return void
     */
    #[Config(self::CONFIG_APPLY_TO_API, 1)]
    public function testNewProductKeepsMetaFieldsFromRequest(): void
    {
        $product = $this->saveProduct($this->getNewProductData([
            ['attribute_code' => 'meta_title', 'value' => 'My title'],
        ]));
        $this->productCreated = true;

        $attributes = $this->getCustomAttributes($product);
        $this->assertSame('My title', $attributes['meta_title'] ?? null);
        $this->assertSame('Autogeneration', $attributes['meta_keyword'] ?? null);
    }

    /**
     * An update of an existing product does not fill its empty meta fields, as in the admin form.
     *
     * @return void
     */
    #[
        Config(self::CONFIG_APPLY_TO_API, 1),
        DataFixture(ProductFixture::class, as: 'product'),
    ]
    public function testExistingProductIsNotAutogenerated(): void
    {
        $sku = DataFixtureStorageManager::getStorage()->get('product')->getSku();

        $product = $this->saveProduct([ProductInterface::SKU => $sku, ProductInterface::NAME => 'New name']);

        $this->assertSame('New name', $product[ProductInterface::NAME]);
        $this->assertArrayNotHasKey('meta_title', $this->getCustomAttributes($product));
    }

    /**
     * Get request data of a new simple product
     *
     * @param array $customAttributes
     * @return array
     */
    private function getNewProductData(array $customAttributes): array
    {
        return [
            ProductInterface::SKU => $this->sku,
            ProductInterface::NAME => 'Autogeneration',
            ProductInterface::TYPE_ID => Type::TYPE_SIMPLE,
            ProductInterface::PRICE => 10,
            ProductInterface::STATUS => Status::STATUS_ENABLED,
            ProductInterface::VISIBILITY => Visibility::VISIBILITY_BOTH,
            ProductInterface::ATTRIBUTE_SET_ID => 4,
            'custom_attributes' => $customAttributes,
        ];
    }

    /**
     * Save the product through the API
     *
     * @param array $product
     * @return array
     */
    private function saveProduct(array $product): array
    {
        return $this->_webApiCall(
            [
                'rest' => ['resourcePath' => self::RESOURCE_PATH, 'httpMethod' => Request::HTTP_METHOD_POST],
                'soap' => [
                    'service' => self::SERVICE_NAME,
                    'serviceVersion' => 'V1',
                    'operation' => self::SERVICE_NAME . 'Save',
                ],
            ],
            ['product' => $product]
        );
    }

    /**
     * Get custom attributes of the API response as code => value
     *
     * @param array $product
     * @return array
     */
    private function getCustomAttributes(array $product): array
    {
        return array_column($product['custom_attributes'], 'value', 'attribute_code');
    }
}
